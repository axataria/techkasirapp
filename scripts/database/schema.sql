CREATE FUNCTION enforce_active_sale() RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER SET search_path = techkasir, pg_catalog AS $$
BEGIN
  PERFORM 1 FROM units WHERE id = NEW.unit_id FOR UPDATE;
  IF EXISTS (SELECT 1 FROM sales s WHERE s.unit_id = NEW.unit_id AND NOT EXISTS
    (SELECT 1 FROM v2_customer_returns r WHERE r.sale_id = s.id AND r.received_on IS NOT NULL)) THEN
    RAISE EXCEPTION 'Unit sudah terjual.' USING ERRCODE = '23505';
  END IF;
  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION enforce_active_sale() FROM PUBLIC, anon, authenticated;

CREATE TRIGGER v2_one_active_sale BEFORE INSERT ON sales FOR EACH ROW EXECUTE FUNCTION enforce_active_sale();

